import { test, expect } from '@playwright/test'

test('black theme, original support artwork, favicon and updated site identity', async ({ page, request }) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/')
  await expect(page).toHaveTitle('Fungarium.INFO Encyclopedia')
  await expect(page.locator('.brand')).toHaveAttribute('aria-label', 'Fungarium.INFO Encyclopedia home')
  await expect(page.locator('.brand-artwork')).toHaveAttribute('src', '/branding/fungarium-mark.png')
  await expect.poll(() => page.locator('.brand-artwork').evaluate(image => image.naturalWidth)).toBe(192)
  expect(await page.locator('body').evaluate(element => getComputedStyle(element).backgroundColor)).toBe('rgb(9, 9, 9)')
  await expect(page.locator('meta[name="theme-color"]')).toHaveAttribute('content', '#090909')
  const favicon = await request.get('/icons/favicon-32x32.png')
  expect(favicon.ok()).toBe(true)
  expect(favicon.headers()['content-type']).toContain('image/png')
  const manifest = await (await request.get('/site.webmanifest')).json()
  expect(manifest.name).toBe('Fungarium.INFO Encyclopedia')
  expect(manifest.background_color).toBe('#090909')
  await page.screenshot({ path: 'test-results/encyclopedia-dark-desktop.png' })
  await page.getByRole('button', { name: 'About the journal' }).click()
  await expect(page.locator('.about-dialog h2')).toContainText('Fungarium.INFO')
  await expect(page.locator('.about-dialog')).toHaveCSS('background-color', 'rgb(20, 20, 20)')
})

test('DMS and older decimal coordinate links open Google Maps at the exact encounter', async ({ page }) => {
  await page.goto('/#/fungi/boletus-edulis')
  const encounters = page.locator('.encounter')
  const newest = encounters.first().locator('.coordinates-link')
  await expect(newest).toBeVisible()
  await expect(newest).toHaveAttribute('target', '_blank')
  const current = new URL(await newest.getAttribute('href'))
  expect(current.searchParams.get('query')).toBe('59.3857500,25.3962778')
  await expect(newest).toContainText('59°23\'08.7"N')
  await encounters.last().locator('summary').first().click()
  const older = new URL(await encounters.last().locator('.coordinates-link').getAttribute('href'))
  expect(older.searchParams.get('query')).toBe('57.9846370,27.6217640')
  await expect(page).toHaveTitle('Boletus edulis — Fungarium.INFO Encyclopedia')
})

test('dark profile and original branding fit small screens', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 800 })
  await page.goto('/')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByRole('button', { name: 'Toggle navigation' }).click()
  await expect(page.locator('.site-header nav')).toHaveCSS('background-color', 'rgb(17, 17, 16)')
  await page.goto('/#/fungi/amanita-muscaria')
  await expect(page.locator('.mycology-panel')).toBeVisible()
  await expect(page.locator('.mycology-card').first()).toHaveCSS('background-color', 'rgb(27, 27, 27)')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: 'test-results/encyclopedia-dark-mobile.png', fullPage: true })
})
