import { test, expect } from '../helpers/browser.js'

test('thumbnail class links replace narrower taxonomy, preserve other filters, and support keyboard and history', async ({ page }) => {
  await page.goto('/#/?genus=Boletus&q=boletus&scope=scientific&organisms=fungi&sc.stipe=reticulate&mc.hymenium=pores&sort=newest')
  const original = page.url()
  const card = page.locator('.species-card').first()
  const link = card.getByRole('link', { name: 'Show class Agaricomycetes', exact: true })
  await expect(card.locator('.card-taxonomy')).toContainText(/Boletaceae\s*\/\s*Agaricomycetes/)
  await expect(card.locator('a a')).toHaveCount(0)
  const href = await link.getAttribute('href')
  const query = new URLSearchParams(href.split('?')[1])
  expect(query.get('class')).toBe('Agaricomycetes')
  expect(query.has('genus')).toBe(false)
  expect(query.has('family')).toBe(false)
  expect(query.get('sc.stipe')).toBe('reticulate')
  expect(query.get('organisms')).toBe('fungi')
  expect(query.get('mc.hymenium')).toBe('pores')
  await link.focus()
  await page.keyboard.press('Enter')
  await expect(page).toHaveURL(new URL(href, original).href)
  await expect(page.getByRole('button', { name: 'Remove class filter', exact: true })).toBeVisible()
  await expect(page.locator('#collection-filters')).toBeHidden()
  for (const name of await page.locator('.card-class').allTextContents()) expect(name).toBe('Agaricomycetes')
  await expect(page.locator('.card-class').first()).toHaveAttribute('aria-current', 'true')
  await page.reload()
  await page.getByRole('button', { name: /^Filters/ }).click()
  await expect(page.getByLabel('Filter by taxonomy class')).toHaveValue('Agaricomycetes')
  await expect(page.getByLabel('Filter by family')).toHaveValue('')
  await page.goBack()
  await expect(page).toHaveURL(original)
  await page.goForward()
  await expect(page.getByLabel('Filter by taxonomy class')).toHaveValue('Agaricomycetes')
  await page.locator('.species-card a.card-family').first().click()
  await expect(page).toHaveURL(/family=Boletaceae/)
  await expect(page).not.toHaveURL(/class=/)
  await expect(page.getByLabel('Filter by taxonomy class')).toHaveValue('')
  const speciesLink = page.locator('.species-card-link').first()
  const target = new URL(await speciesLink.getAttribute('href'), page.url()).href
  await speciesLink.locator('.card-caption').click()
  await expect(page).toHaveURL(target)
})

test('class dropdown filters the catalog and clear taxonomy resets classes independently', async ({ page }) => {
  await page.goto('/#/?organisms=slime-moulds')
  await page.getByRole('button', { name: /^Filters/ }).click()
  const select = page.getByLabel('Filter by taxonomy class')
  await select.selectOption('Protosteliomycetes')
  await expect(page.locator('.species-card')).toHaveCount(1)
  await expect(page.locator('.card-caption em')).toHaveText('Ceratiomyxa fruticulosa')
  await expect(page.locator('.card-class')).toHaveText('Protosteliomycetes')
  await page.getByRole('button', { name: 'Clear taxonomy', exact: true }).click()
  await expect(select).toHaveValue('')
  await expect(page).not.toHaveURL(/class=/)
  await expect(page).toHaveURL(/organisms=slime-moulds/)
  await expect(page.locator('.species-card')).toHaveCount(7)
  await select.selectOption('Myxogastria')
  await expect(page.locator('.species-card')).toHaveCount(6)
  await page.getByRole('button', { name: 'Remove class filter', exact: true }).click()
  await expect(page.locator('.species-card')).toHaveCount(7)
  await select.selectOption('Agaricomycetes')
  await expect(page.getByText('No discoveries here just yet.')).toBeVisible()
  await page.getByRole('button', { name: 'Clear all filters', exact: true }).click()
  await expect(select).toHaveValue('')
  await expect(page.locator('.species-card')).toHaveCount(36)
})

test('mixed taxonomy URLs normalize genus before family before class', async ({ page }) => {
  await page.goto('/#/?class=Myxogastria&family=Boletaceae')
  await expect(page).not.toHaveURL(/class=/)
  await expect(page.getByRole('button', { name: 'Remove family filter' })).toBeVisible()
  await page.goto('/#/?class=Myxogastria&family=Boletaceae&genus=Boletus')
  await expect(page).not.toHaveURL(/class=|family=/)
  await expect(page.locator('.species-card')).toHaveCount(2)
  await expect(page.getByRole('button', { name: 'Remove genus filter' })).toBeVisible()
})

test.describe('mobile class links', () => {
  test.use({ viewport: { width: 320, height: 800 }, isMobile: true, hasTouch: true })

  test('family/class labels fit small cards, class taps filter, and photo taps open the species', async ({ page }) => {
    await page.goto('/#/?q=Boletus%20edulis&scope=scientific')
    const card = page.locator('.species-card').first()
    const family = card.locator('.card-family')
    const taxonomicClass = card.locator('.card-class')
    await card.scrollIntoViewIfNeeded()
    for (const link of [family, taxonomicClass]) {
      const bounds = await link.boundingBox()
      expect(bounds.width).toBeGreaterThanOrEqual(24)
      expect(bounds.height).toBeGreaterThanOrEqual(24)
    }
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await card.screenshot({ path: 'test-results/taxonomy-class-card-mobile.png' })
    await taxonomicClass.tap()
    await expect(page).toHaveURL(/class=Agaricomycetes/)
    await expect(page).not.toHaveURL(/fungi\//)
    await expect(page.getByRole('button', { name: 'Remove class filter' })).toBeVisible()
    await page.getByRole('button', { name: /^Filters/ }).click()
    await expect(page.getByLabel('Filter by taxonomy class')).toHaveValue('Agaricomycetes')
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.getByRole('button', { name: /^Show 1 species/ }).click()
    await page.locator('.species-card-link').first().tap()
    await expect(page).toHaveURL(/#\/fungi\/boletus-edulis$/)
  })
})
