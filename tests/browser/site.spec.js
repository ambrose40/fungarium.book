test('filters are optional, preserve selections when closed, and return to photos', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  const toggle = page.getByRole('button', { name: /^Filters/ })
  await expect(page.locator('#collection-filters')).toBeHidden()
  await toggle.click()
  await page.getByLabel('Filter by family').selectOption('Boletaceae')
  const count = await page.locator('.species-card').count()
  await expect(toggle).toContainText('1')
  await page.getByRole('button', { name: /^Show \d+ species/ }).click()
  await expect(toggle).toHaveAttribute('aria-expanded', 'false')
  await expect(page.locator('.species-card').first()).toBeInViewport({ ratio: 1 })
  await expect(page.locator('.species-card')).toHaveCount(count)
  await expect(page.getByRole('button', { name: 'Remove family filter' })).toBeVisible()
  await toggle.click()
  await expect(page.getByLabel('Filter by family')).toHaveValue('Boletaceae')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await toggle.click()
  await page.getByRole('button', { name: 'Remove family filter' }).click()
  await expect(page.locator('.species-card')).toHaveCount(36)
})
