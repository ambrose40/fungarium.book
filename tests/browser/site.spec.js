import { test, expect } from '@playwright/test'

test('gallery search, filters, load-more, and species navigation', async ({ page }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: /The collection/ })).toBeVisible()
  await expect(page.locator('.species-card')).toHaveCount(36)
  await page.getByRole('button', { name: 'More discoveries' }).click()
  await expect(page.locator('.species-card')).toHaveCount(72)
  await page.getByRole('searchbox').fill('boletus edulis')
  await expect(page.locator('.species-card')).toHaveCount(1)
  await page.locator('.species-card').click()
  await expect(page).toHaveURL(/#\/fungi\/boletus-edulis$/)
  await expect(page.locator('.species-heading h1')).toHaveText('Boletus edulis')
  await expect(page.locator('.source-label')).toContainText('2025')
  await expect(page.locator('.encounter')).toHaveCount(4)
  await expect(page.locator('.taxonomy-list')).toContainText('Boletales')
  await page.getByRole('link', { name: 'Field encounters 4' }).click()
  await expect(page).toHaveURL(/#\/fungi\/boletus-edulis$/)
  await expect(page.locator('.encounter').first()).toHaveAttribute('open', '')
  await page.locator('.encounter').last().locator('summary').first().click()
  await expect(page.locator('.encounter').last().locator('.encounter-body')).toBeVisible()
  await expect(page.locator('.encounter').last().locator('.encounter-meta')).toContainText('Sony Cyber-shot DSC-HX99')
  await page.locator('.encounter').first().getByText('Read the full original caption').click()
  await expect(page.locator('.encounter').first().locator('.original-caption p')).toContainText('🆔 Boletus edulis')
  await expect(page.locator('.encounter').first().getByRole('link', { name: /Original Instagram post/ })).toHaveAttribute('href', 'https://www.instagram.com/p/DPaq0gVjEP0/')
  await page.getByRole('link', { name: 'Back to the collection' }).click()
  await expect(page).toHaveTitle('Fungarium.INFO Encyclopedia')
  await expect(page.locator('.species-card')).toHaveCount(36)
  expect(errors).toEqual([])
})

test('multilingual search, family/year filters, empty states and hashtags', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('searchbox').fill('Punane kärbseseen')
  await expect(page.locator('.species-card')).toHaveCount(1)
  await page.getByRole('button', { name: 'Clear filters' }).click()
  await page.getByLabel('Filter by family').selectOption('Boletaceae')
  await page.getByLabel('Filter by observation year').selectOption('2025')
  await expect(page.locator('.species-card').first()).toBeVisible()
  for (const family of await page.locator('.card-family').allTextContents()) expect(family).toBe('Boletaceae')
  await page.getByRole('searchbox').fill('there-is-no-such-species')
  await expect(page.getByText('No discoveries here just yet.')).toBeVisible()
  await page.getByRole('button', { name: 'Reset filters' }).click()
  await expect(page.locator('.species-card')).toHaveCount(36)
  await page.goto('/#/fungi/boletus-edulis')
  await page.locator('.hashtag-list').getByRole('link', { name: '#boletusedulis', exact: true }).click()
  await expect(page.locator('.tag-filter')).toContainText('#boletusedulis')
  await expect(page.locator('.species-card')).toHaveCount(1)
  await page.getByRole('button', { name: 'Remove hashtag filter' }).click()
  await expect(page.locator('.species-card')).toHaveCount(36)
})

test('mobile layouts, navigation dialog and direct detail links', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await expect(page.locator('.hero-photo img[data-active="true"]')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: 'test-results/gallery-mobile.png', fullPage: true })
  await page.getByRole('button', { name: 'Toggle navigation' }).click()
  await page.getByRole('button', { name: 'About the journal' }).click()
  await expect(page.locator('dialog.about-dialog')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.locator('dialog.about-dialog')).not.toBeVisible()
  await page.goto('/#/fungi/amanita-muscaria')
  await expect(page.locator('.species-heading h1')).toContainText('Amanita muscaria')
  await expect(page.locator('.source-label')).toContainText('2026')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: 'test-results/detail-mobile.png', fullPage: true })
  await page.goto('/#/fungi/not-a-real-species')
  await expect(page.getByRole('heading', { name: /isn’t in the journal/ })).toBeVisible()
})

test('desktop visual capture and exploration anchor stays on the gallery', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/')
  await page.evaluate(() => document.fonts.ready)
  await page.screenshot({ path: 'test-results/gallery-desktop.png', fullPage: false })
  await page.getByRole('link', { name: 'Explore the collection' }).click()
  await expect(page).not.toHaveURL(/collection/)
  await page.locator('#collection').scrollIntoViewIfNeeded()
  await page.screenshot({ path: 'test-results/collection-desktop.png', fullPage: false })
  await page.goto('/#/fungi/boletus-edulis')
  await page.screenshot({ path: 'test-results/detail-desktop.png', fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
