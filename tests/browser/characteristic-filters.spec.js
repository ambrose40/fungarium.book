import { test, expect } from '@playwright/test'

async function openGroup(page, id) {
  const group = page.locator(`[data-characteristic-filter="${id}"]`)
  if (await group.getAttribute('open') === null) await group.locator('summary').click()
  return group
}

test('mycological filters refine genus results, retain multiple values and survive reloads', async ({ page }) => {
  await page.goto('/#/?genus=Amanita')
  await expect(page.locator('.characteristic-filter-group')).toHaveCount(12)
  await openGroup(page, 'spore-print')
  await page.getByRole('checkbox', { name: 'Spore print / mass colour: White', exact: true }).check()
  await openGroup(page, 'cap')
  await page.getByRole('checkbox', { name: 'Cap shape: Convex', exact: true }).check()
  await page.getByRole('checkbox', { name: 'Cap shape: Flat', exact: true }).check()
  await expect(page.locator('.characteristic-active-chip')).toHaveCount(3)
  await expect(page).toHaveURL(/genus=Amanita/)
  await expect(page).toHaveURL(/mc.spore-print=white/)
  await expect(page.locator('.species-card').first()).toBeVisible()
  for (const name of await page.locator('.card-caption em').allTextContents()) expect(name.startsWith('Amanita ')).toBe(true)
  await page.reload()
  await openGroup(page, 'cap')
  await expect(page.getByRole('checkbox', { name: 'Cap shape: Convex', exact: true })).toBeChecked()
  await expect(page.getByRole('checkbox', { name: 'Cap shape: Flat', exact: true })).toBeChecked()
  await page.getByRole('button', { name: 'Clear Cap shape filter', exact: true }).click()
  await expect(page).not.toHaveURL(/mc.cap=/)
  await expect(page).toHaveURL(/mc.spore-print=white/)
  await expect(page.getByRole('button', { name: 'Remove genus filter' })).toBeVisible()
  await page.getByRole('button', { name: 'Clear characteristics', exact: true }).click()
  await expect(page).not.toHaveURL(/mc\./)
  await expect(page).toHaveURL(/genus=Amanita/)
})

test('genus/family switching and the family dropdown are exclusive while retaining additive characteristics', async ({ page }) => {
  await page.goto('/#/?genus=Amanita&mc.spore-print=white')
  await page.getByLabel('Find a family').fill('Boletaceae')
  await page.getByRole('link', { name: /^Show family Boletaceae \(/ }).click()
  await expect(page).toHaveURL(/family=Boletaceae/)
  await expect(page).not.toHaveURL(/genus=/)
  await expect(page).toHaveURL(/mc.spore-print=white/)
  await expect(page.getByRole('button', { name: 'Remove genus filter' })).toHaveCount(0)
  await page.getByLabel('Find a genus').fill('Amanita')
  await page.getByRole('link', { name: /^Show genus Amanita \(/ }).click()
  await expect(page).not.toHaveURL(/family=/)
  await expect(page.getByLabel('Filter by family')).toHaveValue('')
  await page.getByLabel('Filter by family').selectOption('Agaricaceae')
  await expect(page).not.toHaveURL(/genus=/)
  await expect(page).toHaveURL(/mc.spore-print=white/)
  await page.getByRole('button', { name: 'Clear taxonomy', exact: true }).click()
  await expect(page).not.toHaveURL(/family=/)
  await expect(page).toHaveURL(/mc.spore-print=white/)
})

test('zero-count combinations show an empty state and can be cleared without losing genus', async ({ page }) => {
  await page.goto('/#/?genus=Agaricus')
  await expect(page.locator('.species-card').first()).toBeVisible()
  const count = await page.locator('.species-card').count()
  await openGroup(page, 'spore-print')
  const white = page.getByRole('checkbox', { name: 'Spore print / mass colour: White', exact: true })
  await expect(white.locator('..').locator('small')).toHaveText('0')
  await white.check()
  await expect(page.getByText('No discoveries here just yet.')).toBeVisible()
  await page.getByRole('button', { name: 'Remove Spore print / mass colour White filter', exact: true }).click()
  await expect(page.locator('.species-card')).toHaveCount(count)
  await expect(page).toHaveURL(/genus=Agaricus/)
})

test('clear all resets search, taxonomy, characteristics, list finders and URLs on mobile', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 800 })
  await page.goto('/#/?genus=Amanita&q=amanita&scope=scientific&year=2026&mc.cap=convex&mc.spore-print=white')
  await page.getByLabel('Find a genus').fill('Amanita')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByRole('button', { name: 'Clear all filters', exact: true }).click()
  await expect(page.getByRole('searchbox')).toHaveValue('')
  await expect(page.getByLabel('Search scope')).toHaveValue('all')
  await expect(page.getByLabel('Filter by observation year')).toHaveValue('')
  await expect(page.getByLabel('Find a genus')).toHaveValue('')
  await expect(page.locator('.characteristic-active-chip')).toHaveCount(0)
  await expect(page.locator('.species-card')).toHaveCount(36)
  await expect(page.getByRole('button', { name: 'Clear all filters', exact: true })).toBeDisabled()
  await page.screenshot({ path: 'test-results/characteristic-filters-mobile.png', fullPage: true })
})

test('legacy URLs containing both taxonomies normalize to one selection', async ({ page }) => {
  await page.goto('/#/?genus=Boletus&family=Amanitaceae&mc.cap=convex')
  await expect(page).not.toHaveURL(/family=/)
  await expect(page.getByLabel('Filter by family')).toHaveValue('')
  await expect(page.locator('.species-card')).toHaveCount(2)
  await expect(page.locator('.characteristic-active-chip')).toHaveCount(1)
})
