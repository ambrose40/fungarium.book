import { test, expect } from '../helpers/browser.js'

test('family badges replace genus, preserve other filters, and support keyboard and history navigation', async ({ page }) => {
  await page.goto('/#/?genus=Boletus&q=boletus&scope=scientific&year=2025&sort=newest&mc.hymenium=pores')
  const originalUrl = page.url()
  const badge = page.locator('.species-card a.card-family').first()
  await expect(badge).toHaveText('Boletaceae')
  const expectedQuery = new URLSearchParams(new URL(originalUrl).hash.split('?')[1])
  expectedQuery.delete('genus')
  expectedQuery.set('family', 'Boletaceae')
  const href = await badge.getAttribute('href')
  expect(new URLSearchParams(href.split('?')[1])).toEqual(expectedQuery)
  await expect(page.locator('.species-card a a')).toHaveCount(0)
  await badge.focus()
  await page.keyboard.press('Enter')
  await expect(page).toHaveURL(new URL(href, originalUrl).href)
  await expect(page.getByRole('button', { name: 'Remove family filter' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Remove genus filter' })).toHaveCount(0)
  await expect(page.locator('#collection-filters')).toBeHidden()
  await expect(page.locator('.species-card').first()).toBeVisible()
  for (const name of await page.locator('.card-family').allTextContents()) expect(name).toBe('Boletaceae')
  await expect(page.locator('.species-card a.card-family').first()).toHaveAttribute('aria-current', 'true')

  await page.reload()
  await expect(page.getByRole('button', { name: 'Remove family filter' })).toBeVisible()
  await page.goBack()
  await expect(page).toHaveURL(originalUrl)
  await expect(page.getByRole('button', { name: 'Remove genus filter' })).toBeVisible()
  await page.goForward()
  await expect(page.getByRole('button', { name: 'Remove family filter' })).toBeVisible()

  const speciesLink = page.locator('.species-card-link').first()
  const speciesHref = await speciesLink.getAttribute('href')
  await speciesLink.locator('.card-caption').click()
  await expect(page).toHaveURL(new URL(speciesHref, originalUrl).href)
  await expect(page.locator('.species-heading h1')).toBeVisible()
})

