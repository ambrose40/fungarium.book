import { test, expect } from '@playwright/test'

test('dedicated scientific search and all-fields mode work with shareable URLs', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: /^Filters/ }).click()
  await page.getByLabel('Search scope').selectOption('scientific')
  await page.getByRole('searchbox').fill('  BOLETUS   EDULIS ')
  await expect(page.locator('.species-card')).toHaveCount(1)
  await expect(page.locator('.card-caption em')).toHaveText('Boletus edulis')
  await expect(page).toHaveURL(/scope=scientific/)
  await page.reload()
  await page.getByRole('button', { name: /^Filters/ }).click()
  await expect(page.getByLabel('Search scope')).toHaveValue('scientific')
  await expect(page.locator('.species-card')).toHaveCount(1)
  await page.getByRole('searchbox').fill('Punane kärbseseen')
  await expect(page.getByText('No discoveries here just yet.')).toBeVisible()
  await page.getByLabel('Search scope').selectOption('all')
  await expect(page.locator('.species-card')).toHaveCount(1)
  await expect(page.locator('.card-caption em')).toHaveText('Amanita muscaria')
})

test('genus and family quick links are exclusive, remain in sync and support back/forward', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: /^Filters/ }).click()
  const genera = page.getByRole('navigation', { name: 'Genera quick filters' })
  const families = page.getByRole('navigation', { name: 'Families quick filters' })
  await expect(genera.getByRole('link').first()).toBeVisible()
  await expect(families.getByRole('link').first()).toBeVisible()
  await page.getByLabel('Find a family').fill('Boletaceae')
  await families.getByRole('link', { name: /^Show family Boletaceae \(/ }).click()
  await expect(page.getByLabel('Filter by family')).toHaveValue('Boletaceae')
  await expect(page.getByRole('button', { name: 'Remove family filter' })).toBeVisible()
  await page.getByLabel('Find a genus').fill('Boletus')
  await genera.getByRole('link', { name: /^Show genus Boletus \(/ }).click()
  await expect(page.locator('.species-card')).toHaveCount(2)
  for (const name of await page.locator('.card-caption em').allTextContents()) expect(name.startsWith('Boletus ')).toBe(true)
  await expect(page).toHaveURL(/genus=Boletus/)
  await expect(page).not.toHaveURL(/family=/)
  await expect(page.getByLabel('Filter by family')).toHaveValue('')
  await expect(page.getByRole('button', { name: 'Remove family filter' })).toHaveCount(0)
  await expect(genera.getByRole('link', { name: /^Show genus Boletus \(/ })).toHaveAttribute('aria-current', 'true')
  await page.goBack()
  await expect(page.getByRole('button', { name: 'Remove genus filter' })).toHaveCount(0)
  await expect(page.getByLabel('Filter by family')).toHaveValue('Boletaceae')
  await page.goForward()
  await expect(page.locator('.species-card')).toHaveCount(2)
  await page.reload()
  await page.getByRole('button', { name: /^Filters/ }).click()
  await expect(page.getByRole('button', { name: 'Remove genus filter' })).toBeVisible()
  await expect(page.getByLabel('Filter by family')).toHaveValue('')
  await expect(page.locator('.species-card')).toHaveCount(2)
  await page.getByRole('button', { name: 'Remove genus filter' }).click()
  await expect(page).not.toHaveURL(/genus=/)
  await expect(page.getByLabel('Filter by family')).toHaveValue('')
  await expect(page.locator('.species-card')).toHaveCount(36)
  await expect(page.getByRole('button', { name: 'Clear all filters', exact: true })).toBeDisabled()
})

