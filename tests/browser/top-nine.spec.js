import { test, expect } from '../helpers/browser.js'

test('TopNine slides automatically advance, wrap, and suspend while hovered', async ({ page }) => {
  await page.clock.install()
  await page.goto('/')
  const carousel = page.getByRole('region', { name: 'TopNine annual photo collections' })
  const active = carousel.locator('img[data-active="true"]')
  await expect(carousel.locator('.top-nine-slide')).toHaveCount(3)
  await expect(active).toHaveAttribute('src', '/images/fungarium-2024.jpeg')
  for (const year of ['2025', '2026', '2024']) {
    await page.clock.runFor(5000)
    await expect(active).toHaveAttribute('src', `/images/fungarium-${year}.jpeg`)
    await expect(carousel.locator('figcaption')).toContainText(`TopNine ${year}`)
  }
  await carousel.locator('.top-nine-viewport').hover()
  await page.clock.runFor(15000)
  await expect(active).toHaveAttribute('src', '/images/fungarium-2024.jpeg')
  await page.mouse.move(0, 0)
  await page.clock.runFor(5000)
  await expect(active).toHaveAttribute('src', '/images/fungarium-2025.jpeg')
})

test('year, arrow, swipe and playback controls select slides without changing the route', async ({ page }) => {
  await page.clock.install()
  await page.goto('/')
  const carousel = page.getByRole('region', { name: 'TopNine annual photo collections' })
  const active = carousel.locator('img[data-active="true"]')
  await carousel.getByRole('button', { name: 'Pause TopNine slideshow' }).click()
  await page.mouse.move(0, 0)
  await page.clock.runFor(15000)
  await expect(active).toHaveAttribute('src', '/images/fungarium-2024.jpeg')
  await carousel.getByRole('button', { name: 'Show TopNine 2026' }).click()
  await expect(active).toHaveAttribute('src', '/images/fungarium-2026.jpeg')
  await carousel.getByRole('button', { name: 'Next TopNine slide' }).click()
  await expect(active).toHaveAttribute('src', '/images/fungarium-2024.jpeg')
  await page.keyboard.press('ArrowLeft')
  await expect(active).toHaveAttribute('src', '/images/fungarium-2026.jpeg')
  const viewport = carousel.locator('.top-nine-viewport')
  await viewport.dispatchEvent('pointerdown', { pointerType: 'touch', clientX: 200, clientY: 100 })
  await viewport.dispatchEvent('pointerup', { pointerType: 'touch', clientX: 90, clientY: 105 })
  await expect(active).toHaveAttribute('src', '/images/fungarium-2024.jpeg')
  await carousel.getByRole('button', { name: 'Play TopNine slideshow' }).click()
  await page.mouse.move(0, 0)
  await page.clock.runFor(5000)
  await expect(active).toHaveAttribute('src', '/images/fungarium-2025.jpeg')
  await expect(page).not.toHaveURL(/fungarium-2025/)
})

