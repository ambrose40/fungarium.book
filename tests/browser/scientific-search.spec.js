import { test, expect } from '../helpers/browser.js'

async function openDescriptionSearch(page) {
  const toggle = page.getByRole('button', { name: /^Filters/ })
  if (await toggle.getAttribute('aria-expanded') !== 'true') await toggle.click()
  const section = page.locator('.scientific-text-search')
  if (await section.getAttribute('open') === null) await section.locator('summary').click()
}

async function addField(page, id, label, text) {
  await page.getByLabel('Add a search field', { exact: true }).selectOption(id)
  await page.getByRole('button', { name: 'Add field', exact: true }).click()
  const input = page.getByRole('textbox', { name: `Search ${label} descriptions`, exact: true })
  await expect(input).toBeFocused()
  if (text) await input.fill(text)
  return input
}

test('main search scopes include scientific and specialist categories and search only their text', async ({ page }) => {
  await page.goto('/#/?genus=Amanita')
  await page.getByLabel('Search scope').selectOption('trait:cap')
  await page.getByRole('searchbox').fill('scarlet-red')
  await expect(page.locator('.species-card')).toHaveCount(1)
  await expect(page.locator('.card-caption em')).toHaveText('Amanita muscaria')
  await expect(page).toHaveURL(/scope=trait:cap/)
  await page.getByLabel('Search scope').selectOption('trait:stipe')
  await expect(page.getByText('No discoveries here just yet.')).toBeVisible()
  await page.getByRole('button', { name: 'Clear filters', exact: true }).click()
  await page.getByLabel('Search scope').selectOption('trait:plasmodium-phase')
  await page.getByRole('searchbox').fill('watery')
  await expect(page.locator('.species-card-link[href="#/fungi/ceratiomyxa-fruticulosa"]')).toBeVisible()
  await page.reload()
  await expect(page.getByLabel('Search scope')).toHaveValue('trait:plasmodium-phase')
  await expect(page.getByRole('searchbox')).toHaveValue('watery')
})

test('description fields combine with scientific names, persist on reload, and clear independently', async ({ page }) => {
  await page.goto('/#/?q=Boletus%20edulis&scope=scientific')
  await openDescriptionSearch(page)
  await addField(page, 'hymenium', 'Hymenium', 'pores')
  await addField(page, 'stipe', 'Stipe', 'reticulate')
  await addField(page, 'chemical-reactions', 'Chemical reactions', 'KOH')
  await expect(page.locator('.species-card')).toHaveCount(1)
  await expect(page.locator('.scientific-search-chip')).toHaveCount(3)
  await expect(page).toHaveURL(/sc.stipe=reticulate/)
  await page.reload()
  await openDescriptionSearch(page)
  await expect(page.getByRole('textbox', { name: 'Search Stipe descriptions', exact: true })).toHaveValue('reticulate')
  await expect(page.getByRole('textbox', { name: 'Search Chemical reactions descriptions', exact: true })).toHaveValue('KOH')
  await page.getByRole('textbox', { name: 'Search Hymenium descriptions', exact: true }).fill('reticulate')
  await expect(page.getByText('No discoveries here just yet.')).toBeVisible()
  await page.getByRole('button', { name: 'Remove Hymenium description search', exact: true }).click()
  await expect(page.locator('.species-card')).toHaveCount(1)
  await page.getByRole('button', { name: 'Clear description searches', exact: true }).click()
  await expect(page).not.toHaveURL(/sc\./)
  await expect(page.getByRole('searchbox')).toHaveValue('Boletus edulis')
  await expect(page.getByLabel('Search scope')).toHaveValue('scientific')
  await expect(page.locator('.species-card')).toHaveCount(1)
})

test('organism checkboxes support both, fungi only, slime moulds only, neither, and reset', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Filters', exact: true }).click()
  const fungi = page.getByRole('checkbox', { name: 'Show fungi', exact: true })
  const slime = page.getByRole('checkbox', { name: 'Show slime moulds', exact: true })
  await expect(fungi).toBeChecked()
  await expect(slime).toBeChecked()
  await fungi.uncheck()
  await expect(page).toHaveURL(/organisms=slime-moulds/)
  await expect(page.locator('.species-card')).toHaveCount(7)
  await expect(page.locator('.species-card-link[href="/fungi/badhamia-utricularis/"]')).toBeVisible()
  await expect(page.locator('.species-card-link[href="/fungi/tubifera-ferruginosa/"]')).toBeVisible()
  await page.reload()
  await expect(page.locator('.organism-active-chip')).toContainText('Slime moulds only')
  await page.getByRole('button', { name: /^Filters/ }).click()
  await expect(fungi).not.toBeChecked()
  await expect(slime).toBeChecked()
  await slime.uncheck()
  await expect(page).toHaveURL(/organisms=none/)
  await expect(page.getByText('No discoveries here just yet.')).toBeVisible()
  await fungi.check()
  await expect(page).toHaveURL(/organisms=fungi/)
  await expect(page.locator('.results-bar')).toContainText('320 species & taxa')
  await expect(page.locator('.organism-active-chip')).toContainText('Fungi only')
  await page.getByRole('button', { name: 'Clear all filters', exact: true }).click()
  await expect(fungi).toBeChecked()
  await expect(slime).toBeChecked()
  await expect(page.locator('.species-card')).toHaveCount(36)
  await expect(page).not.toHaveURL(/organisms=/)
})

test('family badges and browser history retain description and organism filters', async ({ page }) => {
  await page.goto('/#/?genus=Boletus&organisms=fungi&sc.stipe=reticulate&sort=newest')
  const original = page.url()
  await page.locator('.species-card a.card-family').first().click()
  await expect(page).toHaveURL(/family=Boletaceae/)
  await expect(page).not.toHaveURL(/genus=/)
  await expect(page).toHaveURL(/organisms=fungi/)
  await expect(page).toHaveURL(/sc.stipe=reticulate/)
  await expect(page.locator('.scientific-search-chip')).toContainText('Stipe: reticulate')
  await page.goBack()
  await expect(page).toHaveURL(original)
  await page.goForward()
  await expect(page.getByRole('button', { name: 'Remove family filter' })).toBeVisible()
  await page.reload()
  await expect(page.locator('.scientific-search-chip')).toContainText('Stipe: reticulate')
  await expect(page.locator('.organism-active-chip')).toContainText('Fungi only')
})

